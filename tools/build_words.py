SUFFIXES = sorted("""
    ations ation itions ition tions tion sions sion ions ion ments ment
    nesses ness ances ance ences ence ancy ency ants ant ents ent ables able
    ibles ible ably ibly ings ing ists ist isms ism ities ity ives ive ously
    ious ous izes ized ize ises ised ise ated ates ate ators ator ers er ors
    or ies ied es ed ly ials ial als al ically ical ics ic y e s
""".split(), key=len, reverse=True)


def light_stem(word):
    """Crude suffix stripper: abidance/abiding -> abid, deceive -> deceiv."""
    w = word
    for _ in range(2):
        for suf in SUFFIXES:
            if w.endswith(suf) and len(w) - len(suf) >= 4:
                w = w[:-len(suf)]
                break
        else:
            break
    return w[:-1] + "y" if w.endswith("i") else w


def shared_chunk(w, t, size=6):
    """A run of `size`+ letters starting in the first three letters of w that
    also appears in t (propriety/appropriate, frolicsome/frolicking)."""
    best = ""
    for i in range(min(3, len(w) - size + 1)):
        n = size
        while i + n <= len(w) and w[i:i + n] in t:
            n += 1
        if n - 1 >= size and len(w[i:i + n - 1]) > len(best):
            best = w[i:i + n - 1]
    return best


def leak(w, text):
    """Why `text` gives away the word `w` (lowercase), or None."""
    sw = light_stem(w)
    for t in sorted(set(re.findall(r"[a-z]+", text.lower()))):
        if len(t) < 3 or (w, t) in NOT_A_LEAK:
            continue
        if w in t:
            return "contains the word (%s)" % t
        if len(t) >= 5 and t in w:
            return "contains part of the word (%s)" % t
        if len(t) >= 4 and w.startswith(t):
            return "contains the start of the word (%s)" % t
        cp = len(os.path.commonprefix([t, w]))
        if cp >= 5 and cp >= min(len(t), len(w)) - 3:
            return "shared stem (%s)" % t
        chunk = shared_chunk(w, t)
        if chunk:
            return "shared root '%s' (%s)" % (chunk, t)
        st = light_stem(t)
        scp = len(os.path.commonprefix([st, sw]))
        if st == sw or (scp >= 4 and scp >= max(len(st), len(sw)) - 2):
            return "same stem (%s)" % t
    return None


def split_clauses(d):
    """Split on semicolons that are not inside parentheses."""
    out, depth, cur = [], 0, ""
    for ch in d:
        depth += ch == "("
        depth -= ch == ")"
        if ch == ";" and depth <= 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    out.append(cur.strip())
    return [c for c in out if c]


def strip_leaks(w, d):
    """Cut the parts of d that give w away. Returns (text, [cut reasons])."""
    cuts, kept = [], []
    for clause in split_clauses(d):
        why = leak(w, clause)
        if why:
            # Try dropping a parenthesis or a trailing ", as ..." example.
            for fix in (re.sub(r"\s*\([^()]*\)", "", clause),
                        re.split(r",\s+as\b", clause)[0],
                        re.split(r",\s+as\b", re.sub(r"\s*\([^()]*\)", "", clause))[0]):
                fix = fix.strip(" ,;:")
                if fix and fix != clause and not leak(w, fix) and usable(fix):
                    cuts.append("cut aside: " + why)
                    clause = fix
                    break
            else:
                cuts.append("cut clause: " + why)
                continue
        kept.append(clause)
    text = "; ".join(kept)
    if cuts and text:
        first = re.findall(r"[A-Za-z]+", text)[:1]
        if first and first[0].lower() in FRAGMENT_STARTS:
            return "", cuts                 # "and differences" is no definition
        text = text[0].upper() + text[1:]   # keep the book's sentence case
    return text, cuts


def usable(text):
    words = re.findall(r"[A-Za-z]+", text)
    if not words:
        return False
    # A lone function word or article left over from a cut is not a definition.
    return not (len(words) == 1 and words[0].lower() in {
        "a", "an", "the", "of", "to", "in", "or", "and", "as", "by", "for"})


def fit_length(d):
    """Cut trailing clauses until d fits MAX_DEF."""
    parts = split_clauses(d)
    while len("; ".join(parts)) > MAX_DEF and len(parts) > 1:
        parts.pop()
    return "; ".join(parts)


