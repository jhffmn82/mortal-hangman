def pdf_lines(path, pages):
    try:
        from pypdf import PdfReader
    except ImportError:
        sys.exit("needs pypdf (pip install pypdf); run with python -E -P")
    reader = PdfReader(path)
    lines = []
    for i in range(min(pages, len(reader.pages))):
        lines += (reader.pages[i].extract_text() or "").splitlines()
    return lines


def parse_entries(lines):
    """Return [(headword, pos, definition)] in book order.

    Banner lines are skipped, the list ends at the copyright notice, and
    lines that do not start a new entry are joined to the previous one."""
    entries = []
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith(BANNERS):
            continue
        if line.startswith(END_MARK):
            break
        m = ENTRY.match(line)
        if m:
            entries.append([m.group("word"), m.group("pos"), m.group("defn")])
        elif entries:
            entries[-1][2] += " " + line
        else:
            log("ignored line before the first entry:", line)
    return [tuple(e) for e in entries]


def clean_definition(d):
    d = (d.replace("“", '"').replace("”", '"')
          .replace("‘", "'").replace("’", "'")
          .replace("–", "-").replace("—", "-"))
    d = re.sub(r"\s+", " ", d).strip()
    d = re.sub(r"\s+([,;:.)])", r"\1", d)
    d = d.rstrip(" .;:,")
    if d[:1].islower():                     # the book's sentence case
        d = d[0].upper() + d[1:]
    return d


