#!/usr/bin/env python3
"""Build the word data for Mortal Hangman.

Word list: "5000 Collegiate Words with Brief Definitions" (FreeVocabulary.com,
Steve Baba / EEENI Inc.), pages 1-10 of the user's PDF. Later pages of that
PDF are an unrelated grammar book and are ignored.

Two outputs from the same words, in the same order:
  --definitions wordnet  data/words.js (public): Princeton WordNet glosses,
                         freely licensed. For each word, the sense whose gloss
                         is closest to the book's definition, else the first
                         sense of the book's part of speech.
  --definitions book     data/words-local.js (gitignored, stays on this PC):
                         the book's own definitions, which are licensed for
                         individual use only. index.html loads it after
                         words.js, so when present it overrides it.

Usage (pypdf for both modes, plus nltk for wordnet; a venv is fine):
    python tools/build_words.py PDF --definitions wordnet [--nltk-data DIR]
    python tools/build_words.py PDF --definitions book
        [--out FILE] [--pages 10] [--report decisions.tsv]
        [--samples 15] [--seed 7] [--check-only]

Rules:
  * headwords: A-Z only (no accents, hyphens, spaces, apostrophes), 7+ letters,
    not capitalised (proper nouns), uppercased in the output;
  * book definitions: the book's own text, whitespace-trimmed, trailing period
    removed, in the book's sentence case;
  * WordNet definitions: one gloss (or a clause of it), at most 110
    characters, sentence case, no trailing period;
  * a definition must not give the answer away: a clause (or parenthesis, or
    ", as ..." example) that contains the word or an obvious stem of it is
    cut, or another WordNet sense is tried; if nothing usable remains the
    entry is dropped;
  * slur-like or vulgar entries are dropped.
"""

import argparse
import collections
import json
import math
import os
import random
import re
import sys

BOOK_HEADER = ('// Source: "5000 Collegiate Words with Brief Definitions" '
               "(FreeVocabulary.com), from the user's PDF")
WORDNET_HEADER = ('// Source: word list from "5000 Collegiate Words with Brief '
                  'Definitions" (FreeVocabulary.com); definitions from Princeton '
                  'WordNet 3.x (WordNet licence). Generated by tools/build_words.py')

MIN_LEN = 7        # "longer than 6 letters"
MAX_DEF = 160      # longest book definition kept (clauses are cut to fit)
WN_MAX = 110       # longest WordNet definition (three lines in the game)
LIST_PAGES = 10    # the word list occupies the first 10 PDF pages

# Entries dropped outright as slur-like, vulgar or sexual.
BLOCKLIST = {
    "mulatto",     # dated, offensive racial term
    "niggard",     # slur-like
    "niggardly",   # slur-like
    "genital",     # sexual anatomy
    "venereal",    # sexual
}

# (word, definition token) pairs that look alike but are not a give-away.
NOT_A_LEAK = {
    ("perseverance", "persistence"),
    ("stringency", "strictness"),
}

# A clause left over after a cut that starts with one of these is a fragment.
FRAGMENT_STARTS = {
    "and", "or", "but", "nor", "as", "of", "with", "for", "from", "by",
    "especially", "esp", "usually", "also", "which", "that", "who", "whom",
    "than", "then", "etc",
}

BANNERS = ("5000 Collegiate Words with Brief Definitions", "7-CD Edition")
END_MARK = "Copyright 2002-2009 by EEENI"

POS = r"(?:n|v|adj|adv|prep|conj|interj|inter|pa|ad|pron|pl|Latin|Greek)\."
ENTRY = re.compile(
    r"^(?P<word>[^\s.]+(?: [^\s.]+){0,3}?)\s+"
    r"(?P<pos>" + POS + r"(?:\s*(?:&|or)?\s*(?:n|v|adj|adv|pl)\.)*)\s+"
    r"(?P<defn>\S.*)$")


def log(*a):
    print(*a, file=sys.stderr)


