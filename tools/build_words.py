def headword_problem(word):
    if not re.fullmatch(r"[A-Za-z]+", word):
        if re.search(r"[^\x00-\x7f]", word):
            return "accented or garbled letters"
        return "hyphen, space or apostrophe"
    if len(word) < MIN_LEN:
        return "shorter than %d letters" % MIN_LEN
    if word[0].isupper():
        return "capitalised headword (proper noun)"
    return None


def build(entries):
    rows, report = [], []
    dropped = collections.Counter()
    seen = set()
    trimmed = 0
    for word, pos, defn in entries:
        why = headword_problem(word)
        lw = word.lower()
        if not why and lw in seen:
            why = "duplicate"
        if not why and lw in BLOCKLIST:
            why = "slur-like, vulgar or sexual (blocklist)"
        d = clean_definition(defn)
        if not why and not d:
            why = "empty definition"
        cuts = []
        if not why:
            d2, cuts = strip_leaks(lw, d)
            if not usable(d2):
                why = "definition gives the word away: " + cuts[0].split(": ", 1)[1]
            else:
                d2 = fit_length(d2)
                if len(d2) > MAX_DEF:
                    why = "definition longer than %d characters" % MAX_DEF
        if why:
            dropped[why.split(":")[0].split(" (")[0]] += 1
            report.append((word, "DROP", pos, why, defn.strip()))
            continue
        seen.add(lw)
        if cuts or d2 != d:
            trimmed += 1
        rows.append((lw.upper(), d2, pos))
        report.append((word, "TRIM" if cuts or d2 != d else "KEEP", pos,
                       " | ".join(cuts) or "cut to %d characters" % MAX_DEF
                       if d2 != d or cuts else "", d2))
    return rows, report, dropped, trimmed


def write_js(rows, out, header):
    lines = [header, "window.WORDS = ["]
    for i, (w, d) in enumerate(rows):
        comma = "," if i < len(rows) - 1 else ""
        lines.append("  [%s, %s]%s" % (json.dumps(w), json.dumps(d), comma))
    lines.append("];")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def read_js(path, header):
    with open(path, encoding="ascii") as f:
        text = f.read()
    first, rest = text.split("\n", 1)
    assert first == header, "header line differs"
    assert rest.startswith("window.WORDS = ["), "window.WORDS missing"
    return json.loads(rest[len("window.WORDS = "):].rstrip().rstrip(";"))


def check(path, header, max_len, samples, seed, book=None):
    rows = read_js(path, header)
    problems = []
    seen = set()
    for w, d in rows:
        if not re.fullmatch(r"[A-Z]{%d,}" % MIN_LEN, w):
            problems.append((w, "bad word"))
        if w in seen:
            problems.append((w, "duplicate"))
        seen.add(w)
        first = re.search(r"[A-Za-z0-9]", d)
        if (not d or d != d.strip() or d.endswith(".") or len(d) > max_len
                or not first or first.group().islower()
                or re.search(r";\s*;|;\s*-|\s{2}", d)):
            problems.append((w, "bad definition: " + d))
        why = leak(w.lower(), d)
        if why:
            problems.append((w, why))
        # Independent naive check: the word or its first 6 letters as text.
        low = d.lower()
        if w.lower() in low or w.lower()[:6] in low:
            problems.append((w, "naive stem check: " + d))
    lens = collections.Counter(len(w) for w, _ in rows)
    dl = sorted(len(d) for _, d in rows)
    print("words: %d" % len(rows))
    print("word length distribution:")
    for n in sorted(lens):
        print("  %2d letters: %4d  %s" % (n, lens[n], "#" * (lens[n] // 20)))
    print("definition length: min %d, median %d, max %d; over 90: %d, over 120: %d"
          % (dl[0], dl[len(dl) // 2], dl[-1], sum(x > 90 for x in dl),
             sum(x > 120 for x in dl)))
    print("problems: %d" % len(problems))
    for p in problems:
        print("   ", p)
    rng = random.Random(seed)
    print("%d random samples (seed %d):" % (samples, seed))
    for w, d in rng.sample(rows, samples):
        if book:
            print("  %s\n      book:    %s\n      wordnet: %s" % (w, book.get(w, "?"), d))
        else:
            print("  %-16s %s" % (w, d))
    return not problems


