# Book part-of-speech tags -> WordNet POS ("adv. & adj." gives both).
BOOK_POS = {"n": "n", "v": "v", "adj": "a", "pa": "a", "adv": "r", "ad": "r"}

# Words ignored when comparing a book definition with WordNet glosses.
STOPWORDS = set("""
    a an the of or and to in on at by for with from as into upon onto that
    which who whom whose what this these those it its is are was were be been
    being has have had do does did not no nor any some such one ones
    something someone anything anyone thing things person persons people
    very more most less much many other another same also especially
    usually often etc eg ie make made makes act acts state quality condition
    character manner way kind sort form use used using pertaining pertain
    relating relate related characterized having give given take cause
    causing tending tend capable able fit being certain
""".split())

USAGE_LABEL = re.compile(
    r"^\((?:informal|slang|colloquial|archaic|obsolete|dated|formal|literary|"
    r"rare|nonstandard|old-fashioned|old use|chiefly British|British|Britain|"
    r"US|usually plural|plural)\)\s*", re.I)


def load_wordnet(nltk_dir):
    try:
        import nltk
    except ImportError:
        sys.exit("--definitions wordnet needs nltk (pip install nltk; a venv is fine)")
    if nltk_dir:
        nltk_dir = os.path.abspath(nltk_dir)
        if nltk_dir not in nltk.data.path:
            nltk.data.path.insert(0, nltk_dir)
    try:
        nltk.data.find("corpora/wordnet.zip")
    except LookupError:
        if not nltk_dir:
            sys.exit("WordNet not found; pass --nltk-data DIR to download it there")
        log("downloading WordNet via nltk into", nltk_dir)
        if not nltk.download("wordnet", download_dir=nltk_dir, quiet=True):
            sys.exit("could not download WordNet")
    from nltk.corpus import wordnet as wn
    from nltk.stem.snowball import SnowballStemmer
    wn.ensure_loaded()
    return wn, SnowballStemmer("english").stem


def clean_gloss(g):
    g = g.replace("``", '"').replace("''", '"')
    g = re.sub(r"`([^`']*)'", r"'\1'", g)
    g = g.replace("`", "'")
    g = re.sub(r"\s+", " ", g).strip()
    # NLTK strips quoted examples but leaves their separators and
    # attributions behind ("detestable; ; ; - Edmund Burke").
    parts = [p.strip() for p in g.split(";")]
    g = "; ".join(p for p in parts if p and not p.startswith("-"))
    g = USAGE_LABEL.sub("", g)
    return g.strip(" .;:,")


def strip_parens(g):
    g = re.sub(r"\s*\([^()]*\)", "", g)
    g = re.sub(r"\s*--[^-]+--\s*", " ", g)      # "attributes--a, b, c--that"
    return re.sub(r"\s+", " ", g).strip(" ,;:")


def trim_qualifiers(g):
    """Drop a trailing ", especially ..." or " etc" qualifier."""
    g2 = re.sub(r",? etc$", "", g)
    m = re.search(r",? especially\b", g2)
    if m and len(g2[:m.start()].split()) >= 3:
        g2 = g2[:m.start()]
    return g2.strip(" ,;:")


def sentence_case(g):
    m = re.search(r"[A-Za-z]", g)
    if m and m.group().islower():
        g = g[:m.start()] + m.group().upper() + g[m.end():]
    return g


# Places where a long gloss can end early and still read as a definition.
PHRASE_BREAKS = re.compile(
    r",\s| in order to | so that | so as to | on the basis | according to "
    r"| that | which | who | whose | where | when | by | through | arranged "
    r"| dealing | used | usually | often | typically | especially "
    r"| and (?=[a-z]+ing\b)| (?=[a-z]{3,}ing\b)")


DANGLING = set("""
    and or but nor of to the a an in on at by for with from as into than
    where which that who whom whose when those these this its their his her
    is are was be being
""".split())


def shorten(g, limit=WN_MAX, floor=25):
    """Cut a too-long gloss at the last phrase boundary that fits and leaves
    a complete phrase (no open parenthesis, no dangling "at"/"where those")."""
    if len(g) <= limit:
        return g
    cuts = sorted((m.start() for m in PHRASE_BREAKS.finditer(g)
                   if floor <= m.start() <= limit), reverse=True)
    for pos in cuts:
        out = g[:pos].rstrip(" ,;:-")
        out = re.sub(r"\s+(?:and|or|but)$", "", out).rstrip(" ,;:-")
        words = [x.lower() for x in re.findall(r"[A-Za-z]+", out)]
        if (len(out) >= floor and out.count("(") == out.count(")")
                and out.count("--") % 2 == 0
                and words and words[-1] not in DANGLING
                # no verb left without its object: "for detecting",
                # "a theologian who believes"
                and not words[-1].endswith("ing")
                and not (len(words) > 1 and words[-2] in {"who", "that", "which"})):
            return out
    return g


# Later gloss clauses starting like this are remarks, not definitions.
REMARK_STARTS = FRAGMENT_STARTS | {
    "used", "can", "may", "might", "could", "would", "should", "will", "must",
    "sometimes", "often", "typically", "acts", "disposed", "marked"}

VARIANT_TIERS = ("whole", "cut", "later clause", "later clause cut")

# Never shown in a game hint: VIOLATOR's other sense is "someone who assaults
# others sexually"; PERVERT keeps its gloss minus "especially in sexual behavior".
UNSUITABLE_GLOSS = re.compile(
    r"\b(?:rap(?:e|ed|es|ing|ist)|assaults? \w+ sexually|sexual(?:ly)? "
    r"(?:assault|behavio)\w*)\b", re.I)


def gloss_variants(gloss):
    """Ways to show one sense, as (text, tier), best first:
    whole  - the full gloss or its first clause, optionally without asides;
    cut    - the same, cut at a phrase boundary to fit WN_MAX;
    later clause (and its cut) - a later clause that reads as a definition
    on its own (not "used to show disapproval", not a full sentence)."""
    full = clean_gloss(gloss)
    clauses = [c.strip(" ,;:") for c in split_clauses(full)]
    later = [c for c in clauses[1:]
             if len(c.split()) >= 3
             and c.split()[0].lower() not in REMARK_STARTS
             and not re.match(r"^(?:\S+\s+){1,5}(?:is|are|was|were)\b",
                              strip_parens(c))
             # a subjectless verb: "charges a fee to ...", "acts to ..."
             and not re.match(r"^[a-z]+[^s]s (?:a|an|the|to|its|their)\b", c, re.I)]

    def with_trims(texts):
        return texts + [f(t) for t in texts for f in (
            strip_parens, trim_qualifiers, lambda x: trim_qualifiers(strip_parens(x)))]

    head = with_trims([full] + clauses[:1])
    tail = with_trims(later)
    out, seen = [], set()
    def cuts(texts):
        # the longest cut that fits keeps the most of the gloss
        return sorted((shorten(t) for t in texts),
                      key=lambda x: (len(x) > WN_MAX, -len(x)))

    for tier, texts in (("whole", head), ("cut", cuts(head)),
                        ("later clause", tail), ("later clause cut", cuts(tail))):
        for v in texts:
            v = sentence_case(v)
            if len(v) >= 4 and v not in seen:
                seen.add(v)
                out.append((v, tier))
    return out


class SenseChooser:
    """Pick the WordNet sense whose gloss best matches the book's meaning."""

    MIN_SCORE = 4.0   # at least one content word in common (idf-weighted)
    NEAR = 0.85       # scores this close to the best count as a tie

    def __init__(self, wn, stem):
        self.wn, self._stem, self._cache = wn, stem, {}
        df = collections.Counter()
        n = 0
        for s in wn.all_synsets():
            n += 1
            df.update(set(self.stems(s.definition())))
        self.idf = {k: math.log(n / v) for k, v in df.items()}
        self.idf_default = math.log(n)

    def stem(self, t):
        if t not in self._cache:
            self._cache[t] = self._stem(t)
        return self._cache[t]

    def stems(self, text):
        return [self.stem(t) for t in re.findall(r"[a-z]+", text.lower())
                if t not in STOPWORDS and len(t) > 2]

    def synsets(self, w):
        """Synsets with w as a lemma; for plural headwords (ABORIGINES) the
        noun synsets of the singular."""
        wn = self.wn
        out = []
        for s in wn.synsets(w):
            if s not in out and any(l.name().lower() == w for l in s.lemmas()):
                out.append(s)
        if not out:
            base = wn.morphy(w, wn.NOUN)
            if base and base != w:
                out = [s for s in wn.synsets(base, wn.NOUN)
                       if any(l.name().lower() == base for l in s.lemmas())]
        return out

    def fallback_order(self, w, synsets, book_pos):
        """Book's POS first, WordNet sense order (most frequent first), with
        proper names and instances pushed back; other POS after."""
        pos_rank = {p: i for i, p in enumerate(book_pos)}

        def key(item):
            idx, s = item
            p = "a" if s.pos() == "s" else s.pos()
            lemma = next((l for l in s.lemmas() if l.name().lower() == w),
                         s.lemmas()[0])
            proper = lemma.name()[0].isupper() or bool(s.instance_hypernyms())
            return (pos_rank.get(p, len(pos_rank)), proper, idx)
        return [s for _, s in sorted(enumerate(synsets), key=key)]

    def bag(self, s, w):
        sw = self.stem(w)
        bag = {}

        def add(text, weight):
            for st in self.stems(text):
                if st != sw:
                    bag[st] = max(bag.get(st, 0), weight)
        add(s.definition(), 1.0)
        add(" ".join(l.name().replace("_", " ") for l in s.lemmas()), 1.0)
        add(" ".join(s.examples()), 0.5)
        related = s.hypernyms() + s.similar_tos() + s.also_sees()
        add(" ".join(l.name().replace("_", " ")
                     for r in related for l in r.lemmas()), 0.5)
        return bag

    OTHER_POS = 0.7   # senses outside the book's part of speech count less

    def score(self, s, w, book_stems, book_pos):
        bag = self.bag(s, w)
        total = 0.0
        for b in book_stems:
            weight = bag.get(b)
            if weight is None:
                # weighty/weight, laudation/laud: one stem extends the other
                weight = max((v for k, v in bag.items()
                              if min(len(k), len(b)) >= 5
                              and (k.startswith(b) or b.startswith(k))),
                             default=0) * 0.5
            total += self.idf.get(b, self.idf_default) * weight
        pos = "a" if s.pos() == "s" else s.pos()
        return total * (1.0 if pos in book_pos else self.OTHER_POS)

    def rank(self, w, book_def, book_pos):
        """Return [(synset, how, score)] in the order to try them."""
        syns = self.synsets(w)
        if not syns:
            return []
        order = self.fallback_order(w, syns, book_pos)
        sw = self.stem(w)
        book_stems = set(self.stems(book_def)) - {sw}
        # Penalise other parts of speech only when WordNet has the book's one
        # (the book calls NEOPHYTE an adjective; WordNet has only nouns).
        present = {"a" if s.pos() == "s" else s.pos() for s in syns}
        pos_ok = [p for p in book_pos if p in present] or sorted(present)
        scored = [(s, self.score(s, w, book_stems, pos_ok)) for s in order]
        best = max(sc for _, sc in scored)
        ranked = []
        if best >= self.MIN_SCORE:
            near = [(s, sc) for s, sc in scored if sc >= best * self.NEAR]
            rest = sorted([(s, sc) for s, sc in scored
                           if self.MIN_SCORE <= sc < best * self.NEAR],
                          key=lambda x: -x[1])
            ranked = [(s, "match", sc) for s, sc in near + rest]
        done = {s for s, _, _ in ranked}
        ranked += [(s, "fallback", sc) for s, sc in scored if s not in done]
        return ranked

    def choose(self, w, book_def, book_pos):
        """Return (definition, synset, how, score) or (None, None, reason, 0)."""
        ranked = self.rank(w, book_def, book_pos)
        if not ranked:
            return None, None, "not in WordNet", 0
        first_leak = None
        # Matching senses beat fallback senses; within each group a whole
        # gloss of any sense beats one cut short, which beats a later clause.
        attempts = []
        for group in ("match", "fallback"):
            members = [(i, s, sc) for i, (s, how, sc) in enumerate(ranked) if how == group]
            for want in VARIANT_TIERS:
                for i, s, sc in members:
                    for v, tier in gloss_variants(s.definition()):
                        if tier == want:
                            attempts.append((i, s, group, sc, v, tier))
        unsuitable = False
        for i, s, how, sc, v, tier in attempts:
            why = leak(w, v)
            if why:
                first_leak = first_leak or why
                continue
            if UNSUITABLE_GLOSS.search(v):
                unsuitable = True
                continue
            if len(v) <= WN_MAX:
                label = how + (" (first choice)" if i == 0 else " (after a skip)")
                note = "" if tier == "whole" else " [%s]" % tier
                return v, s.name() + note, label, sc
        if unsuitable:
            return None, None, ("the senses that don't give the word away are "
                                "unsuitable (sexual assault)"), 0
        if first_leak:
            return None, None, "every WordNet sense gives the word away: " + first_leak, 0
        return None, None, "no WordNet gloss of %d characters or less" % WN_MAX, 0


def wordnet_rows(book_rows, nltk_dir):
    wn, stem = load_wordnet(nltk_dir)
    log("indexing WordNet glosses ...")
    chooser = SenseChooser(wn, stem)
    rows, report = [], []
    how_count, dropped = collections.Counter(), []
    for w, book_def, pos in book_rows:
        tags = [BOOK_POS[t] for t in re.findall(r"([a-z]+)\.", pos) if t in BOOK_POS]
        book_pos = list(dict.fromkeys(tags)) or ["n", "v", "a", "r"]
        d, syn, how, sc = chooser.choose(w.lower(), book_def, book_pos)
        if d is None:
            dropped.append((w, how))
            report.append((w, "DROP", pos, how, "", book_def, ""))
            continue
        how_count[how] += 1
        rows.append((w, d))
        report.append((w, how, pos, syn, "%.1f" % sc, book_def, d))
    return rows, report, how_count, dropped


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("pdf", nargs="?", help="the PDF holding the word list")
    ap.add_argument("--definitions", choices=("wordnet", "book"), default="wordnet",
                    help="wordnet: public data/words.js; book: the book's own "
                         "definitions in data/words-local.js (default %(default)s)")
    ap.add_argument("--out", help="output file (default data/words.js for "
                                  "wordnet, data/words-local.js for book)")
    ap.add_argument("--nltk-data", help="folder holding (or to receive) NLTK's WordNet")
    ap.add_argument("--pages", type=int, default=LIST_PAGES,
                    help="PDF pages holding the list (default %(default)s)")
    ap.add_argument("--report", help="write a TSV of every entry's fate here")
    ap.add_argument("--samples", type=int, default=15)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--check-only", action="store_true",
                    help="only verify an existing output file")
    args = ap.parse_args()
    wordnet = args.definitions == "wordnet"
    out = os.path.normpath(args.out or os.path.join(
        here, "..", "data", "words.js" if wordnet else "words-local.js"))
    header = WORDNET_HEADER if wordnet else BOOK_HEADER
    max_len = WN_MAX if wordnet else MAX_DEF
    book = None

    if not args.check_only or wordnet:
        if not args.pdf:
            ap.error("the PDF path is required")
        entries = parse_entries(pdf_lines(args.pdf, args.pages))
        log("entries parsed from the PDF: %d" % len(entries))
        rows, report, dropped, trimmed = build(entries)
        log("words kept from the book: %d (%d with a clause or aside cut)"
            % (len(rows), trimmed))
        for k, v in dropped.most_common():
            log("  dropped: %-45s %d" % (k, v))
        book = {w: d for w, d, _ in rows}

    if not args.check_only:
        if wordnet:
            rows, report, how_count, wn_dropped = wordnet_rows(rows, args.nltk_data)
            log("WordNet definitions: %d" % len(rows))
            for k, v in sorted(how_count.items()):
                log("  %-28s %d" % (k, v))
            log("dropped (no usable WordNet sense): %d" % len(wn_dropped))
            for w, why in wn_dropped:
                log("  %-16s %s" % (w, why))
            columns = "word\thow\tpos\tsynset\tscore\tbook\twordnet\n"
        else:
            rows = [(w, d) for w, d, _ in rows]
            columns = "word\tstatus\tpos\tnote\tdefinition\n"
        write_js(rows, out, header)
        log("wrote", out)
        if args.report:
            with open(args.report, "w", encoding="utf-8", newline="\n") as f:
                f.write(columns)
                for r in report:
                    f.write("\t".join(r) + "\n")
            log("wrote", args.report)

    ok = check(out, header, max_len, args.samples, args.seed,
               book if wordnet else None)
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
